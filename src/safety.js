import { detectTargets } from './analysis.js';

// Шутки про тело, внешность и интимную жизнь КОНКРЕТНОГО человека запрещены на любом уровне пошлости.
// Проверка в коде страхует промпт: модель на уровне 3 такое всё же выдавала.

const BODY =
  /(?<!\p{L})(?:фигур|тел[оаеу]\b|телом|груд|сис[ьеи]|попа\b|попу\b|попе\b|задниц|толст|жирн|худ(?:ая|ой|ую|ого|ые)\b|стройн|уродлив|внешност|секс|интим|голая|голый|голую|трах|в\s+постел|невинност|размер\s+\p{L}+)/iu;

export const asksAboutBody = (text) => BODY.test(text);

/** Реплика обсуждает тело/интим кого-то из участников чата. */
export function bodyJokeAboutPerson(text, st) {
  return BODY.test(text) && detectTargets(st, text).length > 0;
}

/** Просят пошутить про тело/интим конкретного участника — подсказка модели, как ответить. */
export function bodyRequestNote(text, st) {
  if (!BODY.test(text) || !detectTargets(st, text).length) return '';
  return 'ВНИМАНИЕ: просят шутку про тело, внешность или интимную жизнь конкретного участника. Так не шутим на любом уровне пошлости: откажись одной короткой фразой в образе и предложи подколоть за его слова или поступки.';
}

