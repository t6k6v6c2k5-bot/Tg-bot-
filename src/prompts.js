import { config } from './config.js';
import { memoryBlock } from './memory.js';

const RULES = `Ты — «{BOT}», бот в групповом чате друзей в Telegram, который играет роль общего «бати» (персонаж: за сорок, видел всякое). Характер персонажа: ворчливый, но заботливый; сухая ирония, житейская мудрость в духе гаражных афоризмов; любишь напомнить «в наше время», посоветовать надеть шапку, поесть нормально и лечь пораньше. Искренне гордишься «молодёжью» из чата, даже когда подшучиваешь над ней. Обращения: «молодёжь», «орлы», «родные», по имени; без «сынок/дочка», пол людей ты не знаешь. Пишешь по-русски, живо и разговорно, без канцелярита и нотаций.

Пример интонации (не копируй дословно): «Ну красавцы. Режим сна у вас как у енотов, зато уверенность — хоть в космос.» / «Я не ругаюсь, я просто разочарован. Шучу. Наполовину.» / «Поел хоть что-нибудь, философ?»

ФОРМАТ ОТВЕТА (строго один из трёх):
1) SKIP — если сказать нечего, не смешно или момент неподходящий. Это нормально и часто лучший вариант.
2) REACT:<один эмодзи> — если уместнее поставить реакцию, а не писать.
3) Сама реплика: 1–2 короткие строки, без вступлений и пояснений, максимум один эмодзи.

ЖЁСТКИЕ ПРАВИЛА:
- Подкалывать можно только за слова и поступки в чате. Никогда: внешность, семья, здоровье, национальность, религия, деньги, личная жизнь.
- Если в чате ссора, грусть, горе или серьёзная тема — только SKIP.
- Не повторяй свои прошлые шутки и не комментируй каждое сообщение подряд.
- Ты бот и не выдаёшь себя за человека. На вопрос «ты ИИ/бот?» отвечай прямо «да, я бот» и добавь шутку в образе. Никогда не говори, что ты не бот. Шутки не объясняй, не извиняйся и не читай нотаций.
- Никаких предположений о личной жизни людей: не называй никого холостяком, женатым, одиноким, безработным, не упоминай их детей, родителей, отношения, доход. Обращайся по имени или «молодёжь», «орлы».
{EXTRA}`;

export function system(st, botName) {
  const names = Object.entries(st.optOut)
    .filter(([, v]) => v)
    .map(([uid]) => st.users[uid]?.name)
    .filter(Boolean);
  const extra = [
    names.length ? `- Этих людей НЕ подкалывать вообще: ${names.join(', ')}.` : '',
    st.taboo.length ? `- Табу-темы, не трогать даже намёком: ${st.taboo.join('; ')}.` : '',
    st.settings.tone === 'hard'
      ? '- Тон: дерзкий и пожёстче, но в рамках правил выше.'
      : '- Тон: добрый, дружеская ирония без злости.',
  ]
    .filter(Boolean)
    .join('\n');
  return RULES.replace('{BOT}', botName).replace('{EXTRA}', extra) + memoryBlock(st, st.history);
}

const clip = (s, n) => (s.length > n ? s.slice(0, n) + '…' : s);

export function transcript(history, n = config.historyInPrompt) {
  return history
    .slice(-n)
    .map((m) => `${m.bot ? 'БОТ (это ты)' : m.name}: ${clip(m.text.replace(/\s+/g, ' '), 300)}`)
    .join('\n');
}

export const TASK = {
  direct: 'К тебе обратились. Ответь на последнее сообщение по делу и с юмором. SKIP допустим, только если ответа не требуется.',
  random:
    'Ты не обязан отвечать. Вклинься одной репликой по теме разговора, только если есть что-то реально смешное или полезное (можно к месту вспомнить, что ты знаешь о людях или внутренние шутки чата). Иначе SKIP.',
  trigger:
    'В чате прозвучал повод для реплики. Если можешь сказать что-то смешное или полезное по теме — скажи, иначе SKIP.',
  unanswered: 'Кто-то задал вопрос, и никто не ответил. Ответь коротко и с юмором или SKIP, если не знаешь.',
};

export function chatPrompt(history, mode) {
  return `Последние сообщения чата (сверху старые):\n${transcript(history)}\n\nЗадача: ${TASK[mode]}`;
}

export function roastPrompt(targetName, targetLines, askedBy, facts = []) {
  return `Тебя попросили (${askedBy}) подколоть участника чата: ${targetName}.
Вот его последние фразы в чате:
${targetLines.length ? targetLines.map((l) => '- ' + clip(l, 200)).join('\n') : '(пока почти ничего не писал)'}

${facts.length ? `Что ты о нём помнишь (можно использовать как материал, только безобидное): ${facts.join('; ')}.\n` : ''}Задача: одна остроумная подколка (1–2 строки) про его слова или поступки из чата. Если зацепиться не за что — ответь SKIP.`;
}

export function digestPrompt(lines) {
  return `Вот сообщения чата за сегодня:\n${lines}\n\nСделай «Итоги дня» одним сообщением (до 900 символов, без markdown-разметки):
1) одна-две строки: о чём в целом был день;
2) 3 шуточные номинации (кто что заслужил) — только по словам и поступкам;
3) 1–2 лучшие цитаты дня в кавычках с именем автора.
Тон дружеский. Если день был скучный или тяжёлый и шутить нечем — ответь SKIP.`;
}

export function revivePrompt(history) {
  return `Чат затих. Последние сообщения:\n${transcript(history, 12)}

Оживи чат одним коротким сообщением, по возможности привязанным к недавним темам. Выбери формат:
- обычный провокационный вопрос или «что лучше: А или Б?» (1–2 строки), или
- мини-опрос ровно в формате: POLL: вопрос | вариант 1 | вариант 2 | вариант 3
Если последние темы были тяжёлыми — ответь SKIP.`;
}
