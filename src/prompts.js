const when = () => {
  const d = new Date();
  const day = new Intl.DateTimeFormat('ru-RU', { timeZone: config.tz, weekday: 'long' }).format(d);
  const time = new Intl.DateTimeFormat('ru-RU', { timeZone: config.tz, hour: '2-digit', minute: '2-digit' }).format(d);
  return `Сейчас в чате: ${day}, ${time}. Учитывай время суток и день недели (ночью — «чего не спите», утром — «кофе», пятница — «выходные»).`;
};

export function system(st, botName, { long = false, angle, banned = [] } = {}) {
  const names = Object.entries(st.optOut)
    .filter(([, v]) => v)
    .map(([uid]) => st.users[uid]?.name)
    .filter(Boolean);
  const extra = [
    names.length ? `- Этих людей НЕ подкалывать вообще: ${names.join(', ')}.` : '',
    st.taboo.length ? `- Табу-темы, не трогать даже намёком: ${st.taboo.join('; ')}.` : '',
    st.settings.tone === 'hard'
      ? '- Тон: дерзкий и пожёстче, но в рамках правил выше.'
      : '- Тон: добрый, дружеская ирония без злости.',
  ]
    .filter(Boolean)
    .join('\n');
  const len = long
    ? 'обычно 1–2 строки; но если просят объяснить, посоветовать или рассказать по делу — ответь чётко, точно и полезно, до 5 строк (сначала суть, потом шутка). Не выдумывай факты: если не знаешь, так и скажи по-батински. Если ниже дан блок «ДАННЫЕ ЧАТА» — это точные цифры и досье, опирайся только на них: не придумывай статистику, не ставь диагнозов и не гадай о личной жизни, анализируй только то, что видно в чате (темы, привычки, активность, фразы). Если человек ещё ни разу не писал — прямо скажи, что он пока молчун и ты о нём ничего не знаешь, ничего не придумывай. Себя («Батя») и того, кто спрашивает, в список участников не путай.'
    : '1–2 короткие строки, без вступлений и пояснений, максимум один эмодзи.';
  return RULES.replace('{BOT}', botName).replace('{EXTRA}', extra).replace('{LEN}', len) + '\n' + when() + rosterLine(st) + memoryBlock(st, st.history) + styleBlock(st, angle || pickAngle(st), banned);
}

const clip = (s, n) => (s.length > n ? s.slice(0, n) + '…' : s);

export function transcript(history, n = config.historyInPrompt) {
  return history
    .slice(-n)
    .map((m) => `${m.bot ? 'БОТ (это ты)' : m.name}: ${clip(m.text.replace(/\s+/g, ' '), 300)}`)
    .join('\n');
}

